var libItems_=null, libTFCache={};
function libItems(){
  if(libItems_===null){ try{ libItems_=fb.GetLibraryItems(); }catch(e){ libItems_=null; } }
  return libItems_;
}
function libTF(field){
  if(libTFCache.hasOwnProperty(field)) return libTFCache[field];
  var lib=libItems(), out=[];
  if(lib && lib.Count && TF[field]){ try{ out=TF[field].EvalWithMetadbs(lib); }catch(e){ out=[]; } }
  libTFCache[field]=out; return out;
}

var libPathMap=null;
function getHandleByPath(p){
  if(!p) return null;
  if(!libPathMap){
    libPathMap={};
    var lib=libItems();
    if(lib && lib.Count){
      for(var i=0; i<lib.Count; i++){
        var lh=lib[i];
        if(lh && lh.Path) libPathMap[lh.Path]=lh;
      }
    }
  }
  if(libPathMap.hasOwnProperty(p)) return libPathMap[p];
  if(NP && NP.Path===p) return NP;
  try {
    for(var pi=0; pi<plman.PlaylistCount; pi++){
      var it=getItems(pi);
      if(it && it.Count){
        for(var j=0; j<it.Count; j++){
          if(it[j] && it[j].Path===p){
            libPathMap[p]=it[j];
            return it[j];
          }
        }
      }
    }
  } catch(e){}
  return null;
}

